#!/usr/bin/env node
/**
 * Builds the runtime index the Playground template picker imports.
 *
 * Every vendored @astryxdesign/core page template drops "whole": the Playground
 * renders the real page component (`<id>.tsx` default export) verbatim as a
 * single `astryx-frozen` block. No JSX→CanvasItem decomposition — the Astryx
 * pages are single-layout and the compiled trees never matched their fidelity.
 *
 * Runs in `prebuild`, right after generate-astryx-templates.mjs.
 * Output: src/lib/design-systems/generated/astryx-templates/astryx-templates.index.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = resolve(root, 'src/lib/design-systems/generated/astryx-templates')
const MANIFEST = join(DIR, 'astryx-templates.manifest.json')

if (!existsSync(MANIFEST)) {
  console.warn('compile-astryx-templates: no manifest; run generate-astryx-templates.mjs first')
  process.exit(0)
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
const index = manifest.map((e) => ({
  id: e.id,
  name: e.name,
  description: e.description,
  category: e.category,
}))

// Emitted as .ts (not .json) — `next dev --webpack` fails to resolve a JSON
// import from this deep generated path, while a TS module resolves fine.
writeFileSync(
  join(DIR, 'astryx-templates.index.ts'),
  `// GENERATED by scripts/compile-astryx-templates.mjs — do not edit\n` +
  `/* eslint-disable */\n` +
  `export const ASTRYX_TEMPLATE_INDEX = ${JSON.stringify(index, null, 2)} as const;\n`,
)

console.log(`compile-astryx-templates: indexed ${index.length} templates (all whole)`)
